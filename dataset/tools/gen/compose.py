"""One cell -> one timeline (9.19 spec, decisions 1–3; 9.10 D44).

A placement puts a mode's C1 task set into a segment [start, end) with its tasks alive to `alive_until`:

- tasks: the C1 tasks, ids suffixed `-s<k>` (k the placement's index, so two task sets never collide), the C1
  arrive offset kept, shifted to the segment's start; a segment-bound task departs at `alive_until`; a finite task
  (no `depart`) has its `total_work` or `spawn_count` scaled from the C1 value by the ratio of the span it must be
  alive in to the C1 span, and that entry of its `source` map becomes `design` when the value changed (decision 1).
  In a segment of `no_input_below` or less the finite task arrives at the segment's start.
- segment: the C1 segment's mode, attributes, scenario (and familiarity) over [start, end).
- input: the C1 window with the C1's margins kept — start + lead, end − trail (D44); dropped when empty, so a 2 s
  segment shows the task set with no keystroke (decision 3). Within the label segment only: a task set that stays
  past its segment types no more once the focus has moved (decision 2).
- focus: the C1 interval over the segment, the same way.
- operations: each at its C1 fraction of its task's window (D44); dropped with the window.
"""

import copy
import pathlib

import yaml

from wlc.units import parse_us

SCALED = ("total_work", "spawn_count")   # the bound values a span scales (decision 1)

HEADER = ("# GENERATED by dataset/tools/generate.py from dataset/grids.yaml and the C1 timelines — do not\n"
          "# hand-edit; not committed (the set's manifest pins the generator and its inputs by content).\n"
          "# {set}: {desc}. Design — the C1 task sets composed; no realism claim.\n")


def fmt_s(us):
    """Integer microseconds -> the timelines' seconds form (`60s`, `2.5s`)."""
    text = f"{us / 1_000_000:.6f}".rstrip("0").rstrip(".")
    return f"{text}s"


def c1_sets(timelines_dir):
    """{mode: the raw C1 timeline} for every `c1-<mode>.timeline.yaml`."""
    out = {}
    for path in sorted(pathlib.Path(timelines_dir).glob("c1-*.timeline.yaml")):
        mode = path.name[len("c1-"):-len(".timeline.yaml")]
        out[mode] = yaml.safe_load(path.read_text())
    return out


def _scaled_value(key, old, span_us, ref_span_us):
    if key == "total_work":
        new_us = round(parse_us(old) * span_us / ref_span_us / 1000) * 1000   # millisecond precision
        return f"{new_us / 1_000_000:.3f}s", new_us != parse_us(old)
    new = max(1, round(old * span_us / ref_span_us))
    return new, new != old


def _place(c1, k, start, end, alive_until, no_input_below):
    """The tracks of one placement: (segment, tasks, input, focus, operations)."""
    c1 = copy.deepcopy(c1)   # no shared objects between placements (yaml would write anchors)
    seg = c1["segments"][0]
    T = parse_us(seg["to"])
    short = (end - start) <= no_input_below
    tasks = []
    for task in c1["tasks"]:
        t = dict(task)
        t["id"] = f"{task['id']}-s{k}"
        arrive_c1 = parse_us(task["arrive"])
        arrive = start + (0 if short else arrive_c1)
        t["arrive"] = fmt_s(arrive)
        if "depart" in task:
            t["depart"] = fmt_s(alive_until)
        else:
            bind, source = dict(task.get("bind") or {}), dict(task.get("source") or {})
            for key in SCALED:
                if key in bind:
                    bind[key], changed = _scaled_value(key, bind[key], alive_until - arrive, T - arrive_c1)
                    if changed:
                        source[key] = "design"
            t["bind"] = bind
            if source:
                t["source"] = source
        tasks.append(t)

    segment = {key: value for key, value in seg.items() if key not in ("from", "to")}
    segment.update({"from": fmt_s(start), "to": fmt_s(end)})

    windows, window_of = [], {}
    for w in c1.get("input") or []:
        lo, hi = start + parse_us(w["from"]), end - (T - parse_us(w["to"]))
        if lo < hi:
            windows.append({"from": fmt_s(lo), "to": fmt_s(hi), "task": f"{w['task']}-s{k}"})
            window_of[w["task"]] = (parse_us(w["from"]), parse_us(w["to"]), lo, hi)
    focus = []
    for f in c1.get("focus") or []:
        lo, hi = start + parse_us(f["from"]), end - (T - parse_us(f["to"]))
        if lo < hi:
            focus.append({"from": fmt_s(lo), "to": fmt_s(hi), "task": f"{f['task']}-s{k}"})
    operations = []
    for op in c1.get("operations") or []:
        if op["task"] not in window_of:
            continue
        a, b, lo, hi = window_of[op["task"]]
        at = lo + round((parse_us(op["at"]) - a) * (hi - lo) / (b - a))
        operations.append({"at": fmt_s(at), "task": f"{op['task']}-s{k}", "name": op["name"]})
    return segment, tasks, windows, focus, operations


def compose(cell, sets, defn):
    """The cell's timeline as a raw dict: meta, segments, tasks, input, focus, operations."""
    no_input_below = parse_us(defn["no_input_below"])
    segments, tasks, windows, focus, operations = [], [], [], [], []
    for k, (mode, start, end, alive_until) in enumerate(cell["placements"]):
        seg, ts, ws, fs, ops = _place(sets[mode], k, start, end, alive_until, no_input_below)
        segments.append(seg)
        tasks.extend(ts)
        windows.extend(ws)
        focus.extend(fs)
        operations.extend(ops)
    data = {"meta": {"id": cell["id"], "seed": cell["seed"], "demand": "calibration"},
            "segments": segments, "tasks": tasks, "input": windows, "focus": focus}
    if operations:
        data["operations"] = operations
    return data


def describe(cell):
    g = cell["grid"]
    if cell["set"] == "transition-grid":
        return (f"{g['a']} -> {g['b']}, form {g['form']} ("
                f"{'A departs and B arrives' if g['form'] == 'departs' else 'A stays and the focus moves to B'})")
    if cell["set"] == "return-grid":
        return f"{g['a']} -> {g['b']} -> {g['a']}, the middle segment {g['middle']}; {cell['split']} half"
    return (f"{g['a']} lead-in, then {g['b']} and {g['a']} in turn every {g['interval']} "
            f"(interval source {g['interval_source']}); {cell['split']} seed")


def timeline_bytes(cell, sets, defn):
    header = HEADER.format(set=cell["set"], desc=describe(cell))
    return (header + yaml.safe_dump(compose(cell, sets, defn), sort_keys=True)).encode()
