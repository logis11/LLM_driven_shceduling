"""Variant-spec deriver (task-2.4 spec §1).

A variant spec (`*.variant.yaml`) derives timelines from a base timeline
via a closed op set applied to the raw yaml:

    variants:
      - id: c2-p1b                  # output meta.id and filename
        from: c2-p1a.timeline.yaml  # base, relative to the spec file
        ops:
          - rename: {from: python3, to: tracker-miner-fs-3}
          - patch-segment: {index: 1, mode: indexing,
                            attributes: {background_wanted: false}}
          - patch-task: {id: bulk, name: borg, archetype: io-stream}
          - add-task: {id: overlay, name: discord, ...}
          - set-segments: [...]     # wholesale segment-list replacement

Derived files are committed; `check` mode re-derives and fails on drift
(lockfile pattern). The seed is always inherited — a spec cannot change
it, silently or otherwise: C2/C4/C5 byte-discipline depends on shared
seeds + keyed substreams.
"""

import pathlib

import yaml

OPS = ("rename", "patch-segment", "patch-task", "add-task", "set-segments")

HEADER = ("# GENERATED by dataset/tools/derive.py from {spec} — do not "
          "hand-edit.\n# base: {base} + ops; seed inherited from the base "
          "(byte-discipline).\n")


class DeriveError(Exception):
    pass


def apply_ops(base, ops, where):
    data = yaml.safe_load(yaml.safe_dump(base))  # deep copy
    for op_entry in ops:
        (op, arg), = op_entry.items()
        if op not in OPS:
            raise DeriveError(f"{where}: unknown op {op!r}")
        if op == "rename":
            hits = 0
            for task in data["tasks"]:
                if task["name"] == arg["from"]:
                    task["name"] = arg["to"]
                    hits += 1
            if not hits:
                raise DeriveError(f"{where}: rename matched no task "
                                  f"named {arg['from']!r}")
        elif op == "patch-segment":
            index = arg["index"]
            if not 0 <= index < len(data["segments"]):
                raise DeriveError(f"{where}: segment index {index} out of range")
            patch = {k: v for k, v in arg.items() if k != "index"}
            data["segments"][index].update(patch)
        elif op == "patch-task":
            for task in data["tasks"]:
                if task["id"] == arg["id"]:
                    task.update(arg)
                    break
            else:
                raise DeriveError(f"{where}: no task with id {arg['id']!r}")
        elif op == "add-task":
            if any(t["id"] == arg["id"] for t in data["tasks"]):
                raise DeriveError(f"{where}: add-task id {arg['id']!r} exists")
            data["tasks"].append(dict(arg))
        elif op == "set-segments":
            data["segments"] = list(arg)
    return data


def derive_spec(spec_path):
    """Yields (out_path, content_bytes) for every variant in a spec file."""
    spec_path = pathlib.Path(spec_path)
    spec = yaml.safe_load(spec_path.read_text())
    for variant in spec["variants"]:
        where = f"{spec_path.name}:{variant.get('id', '?')}"
        if "seed" in variant or any("seed" in (op.get("patch-meta") or {})
                                    for op in variant.get("ops", [])
                                    if isinstance(op, dict)):
            raise DeriveError(f"{where}: variants may not change the seed")
        base_path = spec_path.parent / variant["from"]
        base = yaml.safe_load(base_path.read_text())
        derived = apply_ops(base, variant.get("ops", []), where)
        derived["meta"]["id"] = variant["id"]
        content = (HEADER.format(spec=spec_path.name, base=variant["from"])
                   + yaml.safe_dump(derived, sort_keys=True))
        out_path = spec_path.parent / f"{variant['id']}.timeline.yaml"
        yield out_path, content.encode()


def run(timelines_dir, check=False):
    """Derive every spec under timelines_dir. Returns error strings."""
    errors = []
    for spec_path in sorted(pathlib.Path(timelines_dir).glob(
            "**/*.variant.yaml")):
        try:
            for out_path, content in derive_spec(spec_path):
                if check:
                    if not out_path.exists():
                        errors.append(f"{out_path.name}: missing (derive drift)")
                    elif out_path.read_bytes() != content:
                        errors.append(f"{out_path.name}: differs from its "
                                      "variant spec (derive drift)")
                else:
                    out_path.write_bytes(content)
        except DeriveError as err:
            errors.append(str(err))
    return errors
