#!/usr/bin/env python3
"""Render the campaign results record (markdown) from pool.py outputs.

render_results.py <results-dir> <out.md>
Reads <results-dir>/pool-<app>.json and reports/<family>-<app>-r<k>.report.json.
"""

import glob
import json
import os
import sys

ORDER = ["soffice", "code", "thunderbird", "chrome", "gimp", "kdenlive", "mpv-video", "mpv-audio", "webrtc"]


def f(v, nd=2):
    return "—" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def spread(vals, nd=3):
    vals = [v for v in vals if v is not None]
    return f"{min(vals):.{nd}f}–{max(vals):.{nd}f}" if vals else "—"


def main():
    R, out = sys.argv[1], sys.argv[2]
    lines = ["# Campaign results — pooled per run (generated by render_results.py)", "",
             "Numbers are pooled over the run's repeats (five 600 s driven / 120 s idle / 300 s play phases unless stated); "
             "`spread` is the range of the per-repeat p50. Threads are the top five by CPU. Per-input rules are method §5's (a) first-wake, (b) window minus idle rate, (c) waker (X-server-woken schedule-ins). "
             "Runner: `ubuntu-24.04`, 4 vCPU, kernel per `reports/*.spec.json`.", ""]
    for app in ORDER:
        p = os.path.join(R, f"pool-{app}.json")
        if not os.path.exists(p):
            continue
        d = json.load(open(p))["runs"][app]
        lines.append(f"## `{app}` — {d['version'].strip()[:60]}, repeats {d['repeats']}")
        lines.append("")
        for phase, ph in d["phases"].items():
            lines.append(f"### {phase}: CPU share {spread(ph['cpu_share'], 4)}, wakes/s {spread(ph['wakes_per_s'], 1)}")
            if "operation" in ph:
                o = ph["operation"]
                lines.append(f"- operation `{o['name']}`: {sum(o['n_ok'])} succeeded, {sum(o['n_failed'])} failed over the repeats; "
                             f"duration p50 {f(o['duration_ms']['p50'], 0)} ms, p90 {f(o['duration_ms']['p90'], 0)}, p99 {f(o['duration_ms']['p99'], 0)} "
                             f"(per-repeat p50 {o['duration_ms']['repeat_p50']}); the thread table below is inside the operation windows only")
            roles = ph["roles"][str(d["repeats"][0])] if str(d["repeats"][0]) in ph["roles"] else ph["roles"].get(d["repeats"][0], {})
            if roles:
                lines.append("- processes by role (repeat 1): " + "; ".join(f"{r}: {v['pids']} pid(s), {v['wakes_per_s']} wakes/s, CPU {v['cpu_share']}" for r, v in roles.items()))
            lines.append("")
            lines.append("| thread comm | threads | wakes/s (spread) | gap p50 ms (spread) | gap p90 | run p50 ms | run p90 | run p99 | n |")
            lines.append("|---|---|---|---|---|---|---|---|---|")
            for comm, c in list(ph["threads"].items())[:5]:
                lines.append(f"| `{comm}` | {min(c['threads'])}–{max(c['threads'])} | {spread(c['wakes_per_s'], 1)} | {f(c['gap_ms']['p50'])} ({spread(c['gap_ms']['repeat_p50'], 1)}) | {f(c['gap_ms']['p90'])} | {f(c['run_ms']['p50'], 3)} | {f(c['run_ms']['p90'], 3)} | {f(c['run_ms']['p99'], 3)} | {c['run_ms']['n']} |")
            lines.append("")
            if "per_input" in ph:
                pi = ph["per_input"]
                lines.append(f"Per input ({pi['events']} events per repeat):")
                lines.append("")
                lines.append("| rule | p50 ms | p90 | p99 | per-repeat p50 |")
                lines.append("|---|---|---|---|---|")
                fw, w, wk = pi["first_wake"], pi["window"], pi["waker"]
                lines.append(f"| (a) first-wake run (attributed {spread(fw['attributed_share'], 3)}; latency p50 {f(fw['latency_ms']['p50'])} ms) | {f(fw['run_ms']['p50'], 3)} | {f(fw['run_ms']['p90'], 3)} | {f(fw['run_ms']['p99'], 3)} | {fw['run_ms']['repeat_p50']} |")
                lines.append(f"| (b) window run, raw (window p50 {f(w['len_ms']['p50'], 0)} ms) | {f(w['run_ms']['p50'], 3)} | {f(w['run_ms']['p90'], 3)} | {f(w['run_ms']['p99'], 3)} | {w['run_ms']['repeat_p50']} |")
                lines.append(f"| (b) window run minus idle rate | {f(w['run_ms_minus_idle']['p50'], 3)} | {f(w['run_ms_minus_idle']['p90'], 3)} | {f(w['run_ms_minus_idle']['p99'], 3)} | {w['run_ms_minus_idle']['repeat_p50']} |")
                lines.append(f"| (c) waker run (X wakes per input p50 {f(wk['x_wakes_per_input']['p50'], 1)}; first X wake latency p50 {f(wk['first_x_wake_latency_ms']['p50'])} ms) | {f(wk['run_ms']['p50'], 3)} | {f(wk['run_ms']['p90'], 3)} | {f(wk['run_ms']['p99'], 3)} | {wk['run_ms']['repeat_p50']} |")
                lines.append("")
        if "driven" in d["phases"] and "driven-alt" in d["phases"] and "per_input" in d["phases"]["driven"] and "per_input" in d["phases"]["driven-alt"]:
            a, b = d["phases"]["driven"]["per_input"]["window"]["run_ms_minus_idle"], d["phases"]["driven-alt"]["per_input"]["window"]["run_ms_minus_idle"]
            lines.append("Stimulus sensitivity (method §3, pre-registered): per-input run, rule (b), SWELL-KW (`driven`) against 136M Keystrokes (`driven-alt`):")
            lines.append("")
            lines.append("| stream | p50 ms | p90 | p99 | per-repeat p50 | driven wakes/s |")
            lines.append("|---|---|---|---|---|---|")
            lines.append(f"| SWELL-KW | {f(a['p50'], 3)} | {f(a['p90'], 3)} | {f(a['p99'], 3)} | {a['repeat_p50']} | {spread(d['phases']['driven']['wakes_per_s'], 1)} |")
            lines.append(f"| 136M Keystrokes | {f(b['p50'], 3)} | {f(b['p90'], 3)} | {f(b['p99'], 3)} | {b['repeat_p50']} | {spread(d['phases']['driven-alt']['wakes_per_s'], 1)} |")
            lines.append("")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(lines)} lines")


if __name__ == "__main__":
    main()
