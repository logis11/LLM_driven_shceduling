#!/usr/bin/env python3
"""Wake-definition check (9.5 follow-ups spec, decision 4): the D1-D20 analysis
counted every timehist row as a wake; the follow-up analysis counts a row as a
wake only when a wakeup event precedes it and folds resumes after preemption
into the preceding wake. This runs both definitions over a campaign's released
run folders and reports, per application and phase pooled over repeats, what
the definition changes on data measured unpinned on four vCPUs — where
preemption between the application's own threads is rare, so the two should
differ little. That is the evidence that the definition change and the
single-core pin are separate effects.

wake_check.py <raw-root> [--md out.md] [--json out.json]
  <raw-root> holds the unzipped release assets: interactive/meas-*/ and
  playback/meas-*/ (release meas-ci-2026-09-14).
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze as A  # noqa: E402

FAMILIES = ("interactive", "playback")


def run_dirs(root):
    for fam in FAMILIES:
        base = os.path.join(root, fam)
        if not os.path.isdir(base):
            continue
        for d in sorted(os.listdir(base)):
            if d.startswith("meas-"):
                yield fam, os.path.join(base, d)


def app_of(fam, d):
    return os.path.basename(d).split("-r")[0].replace(f"meas-{fam}-", "")


def collect(root, log=sys.stderr):
    out = {}
    for fam, d in run_dirs(root):
        app = app_of(fam, d)
        for wd in ("row", "wakeup"):
            res, raw = A.analyze_run(d, wake_def=wd)
            for ph, p in raw["phases"].items():
                o = out.setdefault((app, ph, wd), {"wakes": 0, "segments": 0, "span": 0.0, "merged": 0,
                                                   "runs": [], "gaps": [], "win": []})
                rows = p["rows"]
                o["wakes"] += len(rows); o["segments"] += len(p["segments"]); o["span"] += p["span"]
                o["merged"] += res["phases"][ph]["resumes_merged"]
                o["runs"] += [r.run for r in rows]
                by = {}
                for r in rows:
                    by.setdefault(r.tid, []).append(r.t_in)
                for ts in by.values():
                    o["gaps"] += [(b - a) * 1000 for a, b in zip(ts, ts[1:])]
                if "per_input" in p:
                    o["win"] += p["per_input"]["win_run_corr"]
        print("done", d, file=log, flush=True)
    rows = []
    for (app, ph, wd), o in sorted(out.items()):
        rows.append({"app": app, "phase": ph, "def": wd, "wakes_per_s": round(o["wakes"] / o["span"], 2),
                     "merged_share": round(o["merged"] / max(o["segments"], 1), 4),
                     "run_p50": A.pct(o["runs"], .5), "run_p90": A.pct(o["runs"], .9), "run_p99": A.pct(o["runs"], .99),
                     "gap_p50": A.pct(o["gaps"], .5), "gap_p90": A.pct(o["gaps"], .9),
                     "input_run_p50": A.pct(o["win"], .5) if o["win"] else None})
    return rows


def render(rows):
    by = {}
    for r in rows:
        by.setdefault((r["app"], r["phase"]), {})[r["def"]] = r
    lines = ["# Wake-definition check on the D3 campaign data (generated by wake_check.py)", "",
             "Row: every timehist row is a wake (the D1–D20 analysis). Wakeup: a wake needs a wakeup event; a resume after "
             "preemption is folded into the preceding wake (9.5 follow-ups spec, decision 4). Pooled over the run's repeats; "
             "run and gap in ms over all application threads; `merged` is the share of segments folded. Rule (b) `input_run` "
             "sums segments and is listed to show it does not move.", "",
             "| app | phase | wakes/s row → wakeup | merged | run p50 row → wakeup | run p90 | run p99 | gap p50 row → wakeup | input_run p50 row → wakeup |",
             "|---|---|---|---|---|---|---|---|---|"]
    for (app, ph), d in sorted(by.items()):
        a, b = d["row"], d["wakeup"]
        f = lambda k: f"{a[k]} → {b[k]}" if a[k] is not None else "—"
        lines.append(f"| `{app}` | {ph} | {f('wakes_per_s')} | {b['merged_share'] * 100:.1f} % | {f('run_p50')} | "
                     f"{f('run_p90')} | {f('run_p99')} | {f('gap_p50')} | {f('input_run_p50')} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root"); ap.add_argument("--md", default=None); ap.add_argument("--json", default=None)
    args = ap.parse_args()
    rows = collect(args.root)
    if args.json:
        import json
        json.dump(rows, open(args.json, "w"), indent=1)
    md = render(rows)
    if args.md:
        open(args.md, "w").write(md)
    print(md)


if __name__ == "__main__":
    main()
