#!/usr/bin/env python3
"""The rerun's throwaway spec (the 11.2 spec, decisions 6 and 8): a copy of the RQ0 gate spec holding the
criterion's runs alone — the judging files under fixed, oracle and the random seeds, at the primary boot default
under the primary table — with the simulator pinned to the fixed version, and a machine configuration naming it.
Linted before it is written out; never committed.

    python3 rerun_spec.py --simulator simulator@841dc81131cb [--experiment rq0-gate-rerun]
        [--machine harness/runner.yaml] [--out-dir runs]

Writes `<out-dir>/<experiment>.spec.yaml` and `<out-dir>/<experiment>.machine.yaml`. Taken out of the copy: the
alternative boot defaults, the reporting and variant files, the cap band's alternative tables and the guard
exemptions naming them or a file the copy does not hold, the Layer-1 exclusions of files it does not hold, and
every reporting line. Nothing else changes."""
import argparse
import copy
import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "harness" / "tools"))
from harness import evaluator  # noqa: E402

SPEC = REPO / "harness" / "experiments" / "rq0-gate.yaml"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--simulator", required=True)
    ap.add_argument("--experiment", default="rq0-gate-rerun")
    ap.add_argument("--machine", default=str(REPO / "harness" / "runner.yaml"))
    ap.add_argument("--out-dir", default=str(REPO / "runs"))
    args = ap.parse_args()
    doc = yaml.safe_load(SPEC.read_text())
    out = copy.deepcopy(doc)
    judging = list(doc["files"]["judging"])
    out["experiment"] = args.experiment
    out["boot_defaults"] = {"primary": doc["boot_defaults"]["primary"], "alternatives": []}
    out["files"] = {"judging": judging, "reporting": [], "variants": []}
    out["layer1_exclusions"] = [w for w in doc.get("layer1_exclusions") or [] if w in judging]
    out["guard_exemptions"] = [g for g in doc.get("guard_exemptions") or []
                               if g["workload"] in judging and not g.get("tables")]
    out["reporting_lines"] = []
    out["pins"].pop("driver_table_alternatives", None)
    out["pins"]["simulator"] = {"version": args.simulator}
    od = pathlib.Path(args.out_dir)
    od.mkdir(parents=True, exist_ok=True)
    spec_path = od / f"{args.experiment}.spec.yaml"
    spec_path.write_text(f"# throwaway copy of {SPEC.name} for 11.2's rerun — the criterion's runs alone, the simulator "
                         f"pinned to {args.simulator}; generated by {pathlib.Path(__file__).name}, never committed\n"
                         + yaml.safe_dump(out, sort_keys=False, allow_unicode=True))
    machine = yaml.safe_load(pathlib.Path(args.machine).read_text())
    machine["simulator"]["version"] = args.simulator
    machine_path = od / f"{args.experiment}.machine.yaml"
    machine_path.write_text(f"# {pathlib.Path(args.machine).name} with the simulator at {args.simulator}, for 11.2's "
                            "rerun; never committed\n" + yaml.safe_dump(machine, sort_keys=False))
    errors = evaluator.lint_spec(spec_path, evaluator.SPEC_SCHEMA, REPO / machine["build_dir"], REPO)
    for e in errors:
        print("lint:", e, file=sys.stderr)
    print(spec_path)
    print(machine_path)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
