#!/usr/bin/env python3
"""A throwaway copy of the RQ0 gate spec for 11.3's runs (the 11.3 spec, decisions 2, 11 and 12): the criterion's
runs alone — the files named under fixed, oracle and the random seeds, at the primary boot default under the
primary table — with the simulator pinned to the version named, and a machine configuration naming that
simulator's command and the build directory the files are read from. Linted by the harness the runs use before it
is written out; never committed.

    python3 spec_copy.py --experiment NAME --harness DIR --simulator VERSION --sim-command PATH
        --build-dir DIR --judging ID[,ID…] [--reporting ID[,ID…]] [--variants ID[,ID…]]
        [--repin] [--machine harness/runner.yaml] [--out-dir runs]

`--harness` is the harness tree whose evaluator lints the copy: `as-run/harness` beside this script (the RQ0
run's, commit 6086e7e1) or `harness` (the current one). Writes `<out-dir>/<NAME>.spec.yaml` and
`<out-dir>/<NAME>.machine.yaml`. Taken out of the copy: the alternative boot defaults, the files not named, the
cap band's alternative tables and the guard exemptions naming them or a file the copy does not hold, the Layer-1
exclusions of files it does not hold, and every reporting line. With `--repin` the dataset and variants pins name
the working tree's manifests — the second bless (decision 10), which the RQ0 gate spec's pins, naming the first,
do not. Nothing else changes."""
import argparse
import copy
import hashlib
import importlib
import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parents[4]
SPEC = REPO / "harness" / "experiments" / "rq0-gate.yaml"


def ids(text):
    return [w for w in (text or "").split(",") if w]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--experiment", required=True)
    ap.add_argument("--harness", required=True)
    ap.add_argument("--simulator", required=True)
    ap.add_argument("--sim-command", required=True)
    ap.add_argument("--build-dir", required=True)
    ap.add_argument("--judging", required=True)
    ap.add_argument("--reporting", default="")
    ap.add_argument("--variants", default="")
    ap.add_argument("--repin", action="store_true", help="the dataset and variants pins on the working tree's manifests")
    ap.add_argument("--machine", default=str(REPO / "harness" / "runner.yaml"))
    ap.add_argument("--out-dir", default=str(REPO / "runs"))
    args = ap.parse_args()
    sys.path.insert(0, str((REPO / args.harness / "tools").resolve()))
    evaluator = importlib.import_module("harness.evaluator")
    doc = yaml.safe_load(SPEC.read_text())
    out = copy.deepcopy(doc)
    judging, reporting, variants = ids(args.judging), ids(args.reporting), ids(args.variants)
    held = judging + reporting
    out["experiment"] = args.experiment
    out["boot_defaults"] = {"primary": doc["boot_defaults"]["primary"], "alternatives": []}
    out["files"] = {"judging": judging, "reporting": reporting, "variants": variants}
    out["layer1_exclusions"] = [w for w in doc.get("layer1_exclusions") or [] if w in held]
    out["guard_exemptions"] = [g for g in doc.get("guard_exemptions") or []
                               if g["workload"] in held and not g.get("tables")]
    out["reporting_lines"] = []
    out["pins"].pop("driver_table_alternatives", None)
    out["pins"]["simulator"] = {"version": args.simulator}
    if args.repin:
        sha = lambda rel: hashlib.sha256((REPO / rel).read_bytes()).hexdigest()
        out["pins"]["dataset"]["sha256"] = sha(out["pins"]["dataset"]["path"])
        for pin in (out["pins"].get("variants") or {}).values():
            pin["sha256"] = sha(pin["path"])
    od = pathlib.Path(args.out_dir)
    od.mkdir(parents=True, exist_ok=True)
    spec_path = od / f"{args.experiment}.spec.yaml"
    spec_path.write_text(f"# throwaway copy of {SPEC.name} for 11.3 — the criterion's runs on the files named, the "
                         f"simulator pinned to {args.simulator}; generated by {pathlib.Path(__file__).name}, "
                         "never committed\n" + yaml.safe_dump(out, sort_keys=False, allow_unicode=True))
    machine = yaml.safe_load(pathlib.Path(args.machine).read_text())
    machine["simulator"] = {"command": [args.sim_command], "version": args.simulator}
    machine["build_dir"] = args.build_dir
    machine_path = od / f"{args.experiment}.machine.yaml"
    machine_path.write_text(f"# {pathlib.Path(args.machine).name} with the simulator at {args.simulator} "
                            f"({args.sim_command}) and the files read from {args.build_dir}, for 11.3; never "
                            "committed\n" + yaml.safe_dump(machine, sort_keys=False))
    errors = evaluator.lint_spec(spec_path, evaluator.SPEC_SCHEMA, REPO / args.build_dir, REPO)
    for e in errors:
        print("lint:", e, file=sys.stderr)
    print(spec_path)
    print(machine_path)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
